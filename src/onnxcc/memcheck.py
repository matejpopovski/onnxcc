"""Independent verifier for the memory plan of a generated C file.

This module imports nothing from the compiler. It reads the emitted source, because that is the
artifact that ships, and replays the program over a shadow copy of each arena: a write stamps its
region with the value's id, and a read must find that same id on every element. There is no notion
of lifetime here, so a planner bug and a liveness bug look identical: a read finds another value's
stamp. Aliasing is checked the same way, since an alias simply resolves to the value it renames.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

_ARENA = re.compile(r"^static (float|int8_t) ([FQ])\[(\d+)\];$", re.M)
_STEP = re.compile(r"^\s*/\*@ (\d+) (\S+) (.*?) \*/\n\s*(.*)$", re.M)
_ALIAS = re.compile(r"^\s*/\*@ alias (\w+) (\w+) (\d+) (\d+) (\w+) \*/$", re.M)
_ACCESS = re.compile(r"([wr])=(\w+)\[(\d+):(\d+)\]:(\w+)")
_ARENA_POINTER = re.compile(r"\b([FQ]) \+ (\d+)\b")
_ARGUMENT = re.compile(r"\b((?:in|out)\d+)\b")
_KERNEL_CALL = re.compile(r"ox_\w+\(\s*(\w+)(?: \+ (\d+))?")

# Kernels that tolerate their output sharing storage exactly with one input. Listed here again,
# on purpose, rather than imported: this is the verifier's own statement of what is legal.
INPLACE_SAFE = frozenset(
    {
        "Abs",
        "Add",
        "Clip",
        "Div",
        "Exp",
        "HardSigmoid",
        "HardSwish",
        "LeakyRelu",
        "Max",
        "Min",
        "Mul",
        "Neg",
        "PRelu",
        "QLinearAdd",
        "QLinearMul",
        "Sigmoid",
        "Softmax",
        "Sub",
        "Tanh",
    }
)


class PlanViolation(Exception):
    """The generated program can read memory holding something other than what it expects."""


@dataclass(frozen=True)
class Access:
    symbol: str
    start: int
    end: int
    value: str


@dataclass
class Step:
    index: int
    op: str
    write: Access
    reads: list[Access]
    statement: str


@dataclass
class Program:
    arenas: dict[str, int]
    steps: list[Step]
    # Alias lines are positioned among the steps: (number of steps before it, alias, target).
    aliases: list[tuple[int, str, str]] = field(default_factory=list)


def parse(source: str) -> Program:
    arenas = {name: int(size) for _, name, size in _ARENA.findall(source)}
    events = []
    for match in _STEP.finditer(source):
        if match.group(1) != "alias":
            events.append((match.start(), "step", match))
    for match in _ALIAS.finditer(source):
        if int(match.group(3)) != int(match.group(4)):
            raise PlanViolation(f"alias {match.group(1)} changes the element count")
        events.append((match.start(), "alias", match))
    events.sort(key=lambda item: item[0])

    program = Program(arenas, [])
    for _, kind, match in events:
        if kind == "alias":
            program.aliases.append((len(program.steps), match.group(1), match.group(2)))
            continue
        accesses = [
            (mode, Access(symbol, int(start), int(end), value))
            for mode, symbol, start, end, value in _ACCESS.findall(match.group(3))
        ]
        writes = [item for mode, item in accesses if mode == "w"]
        if len(writes) != 1:
            raise PlanViolation(f"step {match.group(1)} must write exactly one tensor")
        reads = [item for mode, item in accesses if mode == "r"]
        program.steps.append(
            Step(int(match.group(1)), match.group(2), writes[0], reads, match.group(4))
        )
    if not program.steps:
        raise PlanViolation("no annotated steps found; was this file generated by onnxcc?")
    return program


def _check_statement(step: Step) -> None:
    """The annotation must describe the code that actually runs on this line."""
    expected = {
        (item.symbol, item.start) for item in [step.write, *step.reads] if item.symbol in "FQ"
    }
    actual = {(name, int(offset)) for name, offset in _ARENA_POINTER.findall(step.statement)}
    if expected != actual:
        raise PlanViolation(
            f"step {step.index}: annotation {sorted(expected)} != code {sorted(actual)}"
        )
    arguments = set(_ARGUMENT.findall(step.statement))
    declared = {item.symbol for item in [step.write, *step.reads] if item.symbol not in "FQ"}
    if arguments != declared:
        raise PlanViolation(f"step {step.index}: arguments {arguments} != {declared}")
    call = _KERNEL_CALL.search(step.statement)
    if call is None:
        raise PlanViolation(f"step {step.index}: no kernel call on the annotated line")
    if call.group(1) != step.write.symbol or int(call.group(2) or 0) != step.write.start:
        raise PlanViolation(f"step {step.index}: first argument is not the declared output")


def _overlap(left: Access, right: Access) -> bool:
    return left.symbol == right.symbol and left.start < right.end and right.start < left.end


def verify(source: str) -> Program:
    program = parse(source)
    shadow = {name: [0] * size for name, size in program.arenas.items()}
    ids: dict[str, int] = {}
    alias: dict[str, str] = {}
    pending = list(program.aliases)
    written: set[str] = set()

    def resolve(value: str) -> str:
        while value in alias:
            value = alias[value]
        return value

    def stamp(value: str) -> int:
        return ids.setdefault(value, len(ids) + 1)

    for position, step in enumerate(program.steps):
        while pending and pending[0][0] <= position:
            _, name, target = pending.pop(0)
            alias[name] = target
        _check_statement(step)
        for item in [step.write, *step.reads]:
            if item.end <= item.start:
                raise PlanViolation(f"step {step.index}: empty region {item}")
            if item.symbol in shadow and item.end > len(shadow[item.symbol]):
                raise PlanViolation(f"step {step.index}: {item} exceeds arena bounds")
        for read in step.reads:
            if not _overlap(read, step.write):
                continue
            exact = (read.start, read.end) == (step.write.start, step.write.end)
            if not (exact and step.op in INPLACE_SAFE):
                raise PlanViolation(f"step {step.index} ({step.op}): illegal overlap with {read}")
        for read in step.reads:
            if read.symbol in shadow:
                region = shadow[read.symbol][read.start : read.end]
                expected = stamp(resolve(read.value))
                if region.count(expected) != len(region):
                    raise PlanViolation(
                        f"step {step.index} ({step.op}): reads {read.value} from a region that "
                        "holds a different value"
                    )
        output = step.write
        if output.value in written:
            raise PlanViolation(f"step {step.index}: {output.value} is written twice")
        written.add(output.value)
        if output.symbol in shadow:
            shadow[output.symbol][output.start : output.end] = [stamp(output.value)] * (
                output.end - output.start
            )
    return program


def check_intervals(
    lifetimes: dict[str, tuple[int, int, int]], offsets: dict[str, int], arena_size: int
) -> None:
    """Pairwise check for planner fuzzing: `lifetimes` maps key to (size, first, last)."""
    keys = sorted(lifetimes)
    if set(keys) != set(offsets):
        raise PlanViolation("plan does not place exactly the requested buffers")
    for key in keys:
        if offsets[key] < 0 or offsets[key] + lifetimes[key][0] > arena_size:
            raise PlanViolation(f"{key} lies outside the arena")
    for position, left in enumerate(keys):
        size_l, first_l, last_l = lifetimes[left]
        for right in keys[position + 1 :]:
            size_r, first_r, last_r = lifetimes[right]
            live_together = first_l <= last_r and first_r <= last_l
            disjoint = (
                offsets[left] + size_l <= offsets[right] or offsets[right] + size_r <= offsets[left]
            )
            if live_together and not disjoint:
                raise PlanViolation(f"{left} and {right} overlap while both are live")
