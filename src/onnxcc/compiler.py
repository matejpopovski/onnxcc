from .planner import Buffer, Plan, make_plan, peak_live
from .quantize import QParams, QuantizeOptions, quantize_graph
from .shapes import infer

ELEMENT_BYTES = {"F": 4, "Q": 1}


@dataclass
class MemoryStats:
    arena_bytes: int  # tensors plus scratch, the whole static RAM a model needs
    scratch_bytes: int
    naive_bytes: int
    peak_live_bytes: int
    constant_bytes: int
    strategy: dict[str, str]


@dataclass
class CompileResult:
    source: str
    header: str
    c_name: str
    prototype: str
    inputs: list[Signature]
    outputs: list[Signature]
    graph: Graph
    memory: MemoryStats
    observed: dict[int, str] = field(default_factory=dict)
    interface: dict[str, QParams] = field(default_factory=dict)
    plans: dict[str, Plan] = field(default_factory=dict)
    buffers: dict[str, list[Buffer]] = field(default_factory=dict)


def _naive_tensor_bytes(graph: Graph) -> int:
    """Bytes if every intermediate tensor had its own array, the baseline a simple emitter hits."""
    caller = set(graph.inputs) | set(graph.outputs)
    total = 0
    for node in graph.nodes:
        for name in node.outputs:
            if name not in caller:
                value = graph.values[name]
                total += value.size * (4 if value.dtype == F32 else 1)
    return total


def _banner(
    graph: Graph, name: str, memory: MemoryStats, steps: int, emitter: Emitter
) -> list[str]:
    return [
        f"Generated by onnxcc {__version__}. Do not edit.",
        f"model {comment_text(graph.name)}, entry point {name}_run",
        "",
        *emitter.describe_io(),
        "",
        f"steps           {steps}",
        f"static RAM      {memory.arena_bytes} bytes, of which {memory.scratch_bytes} scratch",
        f"live peak       {memory.peak_live_bytes} bytes, a lower bound on any plan",
        f"without planner {memory.naive_bytes} bytes",
        f"constants       {memory.constant_bytes} bytes",
    ]


def _header(emitter: Emitter, arena_bytes: int, interface: Mapping[str, QParams]) -> str:
    prefix = emitter.name.upper()
    lines = [
        f"#ifndef {prefix}_H",
        f"#define {prefix}_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define {prefix}_STATIC_RAM_BYTES {arena_bytes}",
    ]
    inputs, outputs = emitter.signature()
    names = [*emitter.graph.inputs, *emitter.graph.outputs]
    for item, name in zip([*inputs, *outputs], names, strict=True):
        lines.append(f"#define {prefix}_{item.name.upper()}_ELEMENTS {item.elements}")
        if name in interface:
            params = interface[name]
            lines.append(
                f"#define {prefix}_{item.name.upper()}_SCALE {float_literal(params.scale)}"
            )
            lines.append(f"#define {prefix}_{item.name.upper()}_ZERO_POINT {params.zero_point}")
    lines += ["", f"{emitter.prototype()};", "", "#endif", ""]
    return "\n".join(lines)


def emit_c(
    graph: Graph,
    name: str,
    strategy: str = "best",
    isolated: bool = False,
    inplace: bool = True,
    observe: bool = False,
    interface: Mapping[str, QParams] | None = None,
) -> CompileResult:
    analysis = analyze(graph, inplace=inplace and not isolated)
    plans = {arena: make_plan(items, strategy) for arena, items in analysis.buffers.items()}
    emitter = Emitter(graph, analysis, plans, name, isolated=isolated, observe=observe)
    # The body registers every constant, so it comes before the banner that reports their size.
    body = emitter.run_body()
    scratch_bytes = emitter.scratch_elements * 4
    arena_bytes = sum(plans[arena].size * ELEMENT_BYTES[arena] for arena in plans) + scratch_bytes
    peak = sum(peak_live(items) * ELEMENT_BYTES[arena] for arena, items in analysis.buffers.items())
    peak += scratch_bytes
    memory = MemoryStats(
        arena_bytes,
        scratch_bytes,
        _naive_tensor_bytes(graph) + scratch_bytes,
        peak,
        emitter.constant_bytes,
        {arena: plan.strategy for arena, plan in plans.items() if plan.size},
    )
    banner = _banner(graph, emitter.name, memory, len(analysis.steps), emitter)
    source = emitter.render(banner, body)
    inputs, outputs = emitter.signature()
    header = _header(emitter, arena_bytes, interface or {})
    return CompileResult(
        source,
        header,
        emitter.name,
        emitter.prototype(),
        inputs,
        outputs,
        graph,
        memory,
        emitter.observed,
        interface=dict(interface or {}),
        plans=plans,
        buffers=analysis.buffers,
    )


def compile_model(
    model: onnx.ModelProto | str | Path,
    name: str | None = None,
    input_shapes: Mapping[str, Sequence[int]] | None = None,
    strategy: str = "best",
    isolated: bool = False,
    inplace: bool = True,
    calibration: Sequence[np.ndarray[Any, Any]] | None = None,
    quantize: QuantizeOptions | None = None,
    fuse: bool = True,
) -> CompileResult:
    graph = import_model(model, input_shapes, name)
    canonicalize(graph)
    interface: dict[str, QParams] = {}
    if quantize is not None:
        if calibration is None:
            raise ValueError("quantization needs calibration samples")
        interface = quantize_graph(graph, calibration, quantize)
        infer(graph)
        graph.eliminate_dead_code()
    if fuse:
        fuse_activations(graph)
    c_name = c_identifier(name or graph.name)
    return emit_c(graph, c_name, strategy, isolated, inplace, interface=interface)


def quantized_graph(
    model: onnx.ModelProto | str | Path,
    calibration: Sequence[np.ndarray[Any, Any]],
    options: QuantizeOptions,
    input_shapes: Mapping[str, Sequence[int]] | None = None,
) -> Graph:
    """The quantized graph before activation fusion, ready for `export.to_onnx`."""
    graph = import_model(model, input_shapes)
    canonicalize(graph)
    quantize_graph(graph, calibration, options)
    infer(graph)
    graph.eliminate_dead_code()
    return graph
